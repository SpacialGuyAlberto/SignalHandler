void Exporter3D::write_ply(
    const std::filesystem::path& path,
    const PointCloud3D& cloud,
    const PlyExportOptions& opts) {
    const auto mode = opts.binary ? (std::ios::out | std::ios::binary | std::ios::trunc)
                                  : (std::ios::out | std::ios::trunc);
    std::ofstream out(path, mode);
    if (!out) {
        throw std::runtime_error("Cannot open PLY file for writing: " + path.string());
    }

    const bool use_utm = (opts.primary_frame == CoordFrame3D::UTM);

    out << "ply\n";
    out << (opts.binary ? "format binary_little_endian 1.0\n" : "format ascii 1.0\n");
    out << "comment Generated by gpr3d SignalHandler\n";
    if (cloud.has_valid_crs) {
        out << "comment CRS_GEODETIC EPSG:4326 (WGS84)\n";
        out << "comment CRS_PROJECTED EPSG:" << cloud.origin_utm.epsg_code()
            << " (UTM Zone " << cloud.origin_utm.zone_string() << ")\n";
        out << std::fixed << std::setprecision(8)
            << "comment ORIGIN_WGS84 lat=" << cloud.origin_wgs84.latitude_deg
            << " lon=" << cloud.origin_wgs84.longitude_deg
            << std::setprecision(3)
            << " alt=" << cloud.origin_wgs84.altitude_m << "\n";
        out << std::setprecision(3)
            << "comment ORIGIN_UTM easting=" << cloud.origin_utm.easting_m
            << " northing=" << cloud.origin_utm.northing_m
            << " elev=" << cloud.origin_utm.elevation_m << "\n";
        out << "comment PRIMARY_XYZ_FRAME " << (use_utm ? "UTM_METERS" : "LOCAL_ENU_METERS") << "\n";
    }
    out << "element vertex " << cloud.points.size() << "\n";
    out << "property double x\n";
    out << "property double y\n";
    out << "property double z\n";
    out << "property uchar red\n";
    out << "property uchar green\n";
    out << "property uchar blue\n";
    out << "property float intensity\n";
    out << "property float amplitude\n";
    out << "property float depth_m\n";
    if (opts.include_geodetic_properties) {
        out << "property double latitude\n";
        out << "property double longitude\n";
    }
    out << "end_header\n";

    if (opts.binary) {
        for (const auto& pt : cloud.points) {
            const double x = use_utm ? pt.utm.easting_m : pt.enu.east_m;
            const double y = use_utm ? pt.utm.northing_m : pt.enu.north_m;
            const double z = use_utm ? pt.utm.elevation_m : pt.enu.up_m;
            const auto rgb = colormap_radar(pt.intensity);

            write_le_scalar<double>(out, x);
            write_le_scalar<double>(out, y);
            write_le_scalar<double>(out, z);
            out.write(reinterpret_cast<const char*>(rgb.data()), 3);
            write_le_scalar<float>(out, pt.intensity);
            write_le_scalar<float>(out, static_cast<float>(pt.amplitude));
            write_le_scalar<float>(out, static_cast<float>(pt.depth_m));
            if (opts.include_geodetic_properties) {
                write_le_scalar<double>(out, pt.wgs84.latitude_deg);
                write_le_scalar<double>(out, pt.wgs84.longitude_deg);
            }
        }
    } else {
        out << std::fixed;
        for (const auto& pt : cloud.points) {
            const double x = use_utm ? pt.utm.easting_m : pt.enu.east_m;
            const double y = use_utm ? pt.utm.northing_m : pt.enu.north_m;
            const double z = use_utm ? pt.utm.elevation_m : pt.enu.up_m;
            const auto rgb = colormap_radar(pt.intensity);

            out << std::setprecision(4) << x << ' ' << y << ' ' << z << ' '
                << static_cast<int>(rgb[0]) << ' '
                << static_cast<int>(rgb[1]) << ' '
                << static_cast<int>(rgb[2]) << ' '
                << std::setprecision(5) << pt.intensity << ' '
                << std::setprecision(4) << pt.amplitude << ' '
                << std::setprecision(4) << pt.depth_m;
            if (opts.include_geodetic_properties) {
                out << ' ' << std::setprecision(8) << pt.wgs84.latitude_deg
                    << ' ' << pt.wgs84.longitude_deg;
            }
            out << '\n';
        }
    }
}

void Exporter3D::write_csv(
    const std::filesystem::path& path,
    const PointCloud3D& cloud) {
    std::ofstream out(path, std::ios::out | std::ios::trunc);
    if (!out) {
        throw std::runtime_error("Cannot open CSV file for writing: " + path.string());
    }

    out << "trace_id,sample_idx,latitude_deg,longitude_deg,altitude_m,"
        << "utm_zone,utm_easting_m,utm_northing_m,"
        << "enu_east_m,enu_north_m,enu_up_m,"
        << "depth_m,twt_ns,amplitude,envelope,intensity,is_peak\n";

    out << std::fixed;
    for (const auto& pt : cloud.points) {
        out << pt.trace_id << ','
            << pt.sample_idx << ','
            << std::setprecision(8) << pt.wgs84.latitude_deg << ','
            << pt.wgs84.longitude_deg << ','
            << std::setprecision(4) << pt.wgs84.altitude_m << ','
            << pt.utm.zone_string() << ','
            << pt.utm.easting_m << ','
            << pt.utm.northing_m << ','
            << pt.enu.east_m << ','
            << pt.enu.north_m << ','
            << pt.enu.up_m << ','
            << pt.depth_m << ','
            << pt.twt_ns << ','
            << pt.amplitude << ','
            << pt.envelope << ','
            << std::setprecision(5) << pt.intensity << ','
            << (pt.is_peak ? 1 : 0) << '\n';
    }
}

void Exporter3D::write_xyz(
    const std::filesystem::path& path,
    const PointCloud3D& cloud,
    CoordFrame3D frame) {
    std::ofstream out(path, std::ios::out | std::ios::trunc);
    if (!out) {
        throw std::runtime_error("Cannot open XYZ file for writing: " + path.string());
    }

    const bool use_utm = (frame == CoordFrame3D::UTM);
    out << "# X Y Z intensity depth_m latitude_deg longitude_deg\n";
    out << std::fixed;
    for (const auto& pt : cloud.points) {
        const double x = use_utm ? pt.utm.easting_m : pt.enu.east_m;
        const double y = use_utm ? pt.utm.northing_m : pt.enu.north_m;
        const double z = use_utm ? pt.utm.elevation_m : pt.enu.up_m;
        out << std::setprecision(4) << x << ' ' << y << ' ' << z << ' '
            << std::setprecision(5) << pt.intensity << ' '
            << std::setprecision(4) << pt.depth_m << ' '
            << std::setprecision(8) << pt.wgs84.latitude_deg << ' '
            << pt.wgs84.longitude_deg << '\n';
    }
}

void Exporter3D::write_auto(
    const std::filesystem::path& path,
    const PointCloud3D& cloud,
    const PlyExportOptions& ply_opts) {
    std::string ext = path.extension().string();
    std::transform(ext.begin(), ext.end(), ext.begin(),
                   [](unsigned char c) { return static_cast<char>(std::tolower(c)); });

    if (ext == ".ply") {
        write_ply(path, cloud, ply_opts);
    } else if (ext == ".csv") {
        write_csv(path, cloud);
    } else if (ext == ".xyz") {
        write_xyz(path, cloud, ply_opts.primary_frame);
    } else {
        throw std::runtime_error(
            "Unsupported 3D export extension '" + ext + "' (expected .ply, .csv, or .xyz)");
    }
}

