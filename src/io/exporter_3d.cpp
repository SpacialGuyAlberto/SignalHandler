/// Smooth geophysical heatmap (deep navy -> cyan -> yellow -> bright red) for intensity in [0, 1].
std::array<std::uint8_t, 3> colormap_radar(float t) noexcept {
    t = std::clamp(t, 0.0f, 1.0f);
    float r = 0.0f;
    float g = 0.0f;
    float b = 0.0f;
    if (t < 0.25f) {
        const float u = t / 0.25f;
        r = 0.05f * (1.0f - u);
        g = 0.15f + 0.65f * u;
        b = 0.45f + 0.55f * u;
    } else if (t < 0.55f) {
        const float u = (t - 0.25f) / 0.30f;
        r = 0.95f * u;
        g = 0.80f + 0.15f * u;
        b = 1.00f * (1.0f - u);
    } else if (t < 0.85f) {
        const float u = (t - 0.55f) / 0.30f;
        r = 0.95f + 0.05f * u;
        g = 0.95f - 0.65f * u;
        b = 0.05f * u;
    } else {
        const float u = (t - 0.85f) / 0.15f;
        r = 1.00f;
        g = 0.30f * (1.0f - u);
        b = 0.05f + 0.25f * u;
    }
    return {
        static_cast<std::uint8_t>(std::clamp(std::lround(r * 255.0f), 0L, 255L)),
        static_cast<std::uint8_t>(std::clamp(std::lround(g * 255.0f), 0L, 255L)),
        static_cast<std::uint8_t>(std::clamp(std::lround(b * 255.0f), 0L, 255L))
    };
}

template <typename T>
void write_le_scalar(std::ofstream& out, T val) {
    static_assert(std::endian::native == std::endian::little || sizeof(T) == 4 || sizeof(T) == 8);
    if constexpr (std::endian::native == std::endian::big) {
        std::array<std::uint8_t, sizeof(T)> bytes{};
        std::memcpy(bytes.data(), &val, sizeof(T));
        std::reverse(bytes.begin(), bytes.end());
        out.write(reinterpret_cast<const char*>(bytes.data()), sizeof(T));
    } else {
        out.write(reinterpret_cast<const char*>(&val), sizeof(T));
    }
}

